// Build only our fixed host libraries with the exact bundled Skulpt compiler.
// User sources, per-source configuration and runtime state are never compiled here.
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const root = path.join(__dirname, '../android/src/main/assets/python-host');
const context = vm.createContext({installPythonPrecompiled() {}});
for (const name of ['skulpt.min.js','skulpt-stdlib.js','html.js','regex.js','json.js','io.js','spider.js']) {
  vm.runInContext(fs.readFileSync(path.join(root, name), 'utf8'), context, {filename:name});
}
let read;
const configure = context.Sk.configure;
context.Sk.configure = options => { read = options.read; configure(options); };
context.createPythonSpider('class Spider: pass\n');
const modules = {};
for (const name of ['src/lib/requests/__init__.py', 'src/lib/json/__init__.py']) {
  const source = read(name);
  const compiled = context.Sk.compile(source, name, 'exec', true);
  modules[name] = [source, compiled.code + '\nvar $builtinmodule = ' + compiled.funcname + ';\n'];
}
process.stdout.write('// Generated by scripts/prepare_python_modules.py; do not edit.\n' +
  'const moviePythonCompiledModules = ' + JSON.stringify(modules) + ';\n' +
  'function installPythonPrecompiled(library) {\n' +
  '  for (const [name, entry] of Object.entries(moviePythonCompiledModules)) {\n' +
  '    if (library[name] === entry[0]) library[name.slice(0, -3) + ".js"] = entry[1];\n' +
  '  }\n' +
  '}\n');
